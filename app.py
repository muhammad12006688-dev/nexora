class PostgresConnection:
    """Small compatibility wrapper so the existing NEXORA code can use ? placeholders."""
    def __init__(self, dsn):
        if psycopg2 is None:
            raise RuntimeError("psycopg2 is not installed. Add psycopg2-binary to requirements.txt")
        self.raw = psycopg2.connect(dsn, cursor_factory=DictCursor)

    def _adapt(self, sql):
        # SQLite -> PostgreSQL syntax compatibility.
        sql = sql.replace("INSERT OR IGNORE INTO", "INSERT INTO")
        sql = sql.replace("INSERT OR REPLACE INTO comment_reactions", "INSERT INTO comment_reactions")
        sql = sql.replace("username COLLATE NOCASE", "LOWER(username)")
        sql = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.I)
        sql = sql.replace("?", "%s")

        # ON CONFLICT behavior used by NEXORA.
        if "INSERT INTO blocks(blocker_id,blocked_id) VALUES(%s,%s)" in sql:
            sql += " ON CONFLICT (blocker_id, blocked_id) DO NOTHING"
        if "INSERT INTO comment_reactions(comment_id,user_id,reaction) VALUES(%s,%s,%s)" in sql:
            sql += " ON CONFLICT (comment_id, user_id) DO UPDATE SET reaction = EXCLUDED.reaction"
        return sql

    def execute(self, sql, params=None):
        # PostgreSQL has no PRAGMA; those checks are handled by column_exists().
        if sql.strip().upper().startswith("PRAGMA "):
            return DummyCursor()
        cur = self.raw.cursor()
        cur.execute(self._adapt(sql), params)
        return cur

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


class DummyCursor:
    def fetchall(self):
        return []
    def fetchone(self):
        return None


def get_db():
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if database_url:
        return PostgresConnection(database_url)
    conn = sqlite3.connect(DB_FILE)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def column_exists(conn, table, column):
    if isinstance(conn, PostgresConnection):
        row = conn.execute(
            "SELECT column_name AS name FROM information_schema.columns WHERE table_schema='public' AND table_name=? AND column_name=?",
            (table, column)
        ).fetchone()
        return bool(row)
    rows = conn.execute(f"PRAGMA table_info({table})").fetchall()
    return any(row["name"] == column for row in rows)


def init_db():
    conn = get_db()

    # POSTS
    conn.execute("""
        CREATE TABLE IF NOT EXISTS posts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            content TEXT NOT NULL,
            category TEXT DEFAULT 'Без категории',
            image TEXT,
            likes INTEGER DEFAULT 0,
            views INTEGER DEFAULT 0,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # USERS
    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL
        )
    """)

    # COMMENTS
    conn.execute("""
        CREATE TABLE IF NOT EXISTS comments (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            post_id INTEGER NOT NULL,
            username TEXT NOT NULL,
            text TEXT NOT NULL,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE
        )
    """)

    # Миграция POSTS
    post_columns = {
        "category": "TEXT DEFAULT 'Без категории'",
        "image": "TEXT",
        "likes": "INTEGER DEFAULT 0",
        "views": "INTEGER DEFAULT 0",
        "created_at": "TEXT"
    }

    for col, definition in post_columns.items():
        if not column_exists(conn, "posts", col):
            conn.execute(f"ALTER TABLE posts ADD COLUMN {col} {definition}")

    # Миграция USERS
    if not column_exists(conn, "users", "role"):
        conn.execute("ALTER TABLE users ADD COLUMN role TEXT DEFAULT 'user'")

    if not column_exists(conn, "users", "created_at"):
        conn.execute("ALTER TABLE users ADD COLUMN created_at TEXT")

    if not column_exists(conn, "users", "avatar"):
        conn.execute("ALTER TABLE users ADD COLUMN avatar TEXT")

    if not column_exists(conn, "posts", "author_id"):
        conn.execute("ALTER TABLE posts ADD COLUMN author_id INTEGER")

    conn.execute("""
        CREATE TABLE IF NOT EXISTS notifications (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            text TEXT NOT NULL,
            link TEXT,
            is_read INTEGER DEFAULT 0,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    """)

    # Миграция COMMENTS
    if not column_exists(conn, "comments", "user_id"):
        conn.execute("ALTER TABLE comments ADD COLUMN user_id INTEGER")

    # Таблица лайков
    conn.execute("""
        CREATE TABLE IF NOT EXISTS post_likes (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            post_id INTEGER NOT NULL,
            user_id INTEGER NOT NULL,
            UNIQUE(post_id, user_id),
            FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    """)

    # Создаём администратора, если его нет.
    admin = conn.execute(
        "SELECT * FROM users WHERE username = ?",
        ("admin",)
    ).fetchone()

    if not admin:
        # Пароль администратора: 1234
        password_hash = generate_password_hash("1234")

        conn.execute("""
            INSERT INTO users
            (username, password, role, created_at)
            VALUES (?, ?, 'admin', ?)
        """, (
            "admin",
            password_hash,
            datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        ))
    else:
        # Делаем существующего admin администратором.
        conn.execute(
            "UPDATE users SET role='admin' WHERE username='admin'"
        )

        # Если старый пароль был SHA-256, оставляем совместимость.
        # При следующем входе он автоматически будет заменён
        # на более безопасный хеш Werkzeug.

    # Заполняем created_at у старых пользователей
    conn.execute("""
        UPDATE users
        SET created_at = COALESCE(created_at, CURRENT_TIMESTAMP::text)
        WHERE created_at IS NULL OR created_at = ''
    """)

    # ================= 8.0: СОЦИАЛЬНЫЕ ФУНКЦИИ =================
    conn.execute("""CREATE TABLE IF NOT EXISTS favorites (id INTEGER PRIMARY KEY AUTOINCREMENT, post_id INTEGER NOT NULL, user_id INTEGER NOT NULL, UNIQUE(post_id,user_id), FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS follows (id INTEGER PRIMARY KEY AUTOINCREMENT, follower_id INTEGER NOT NULL, following_id INTEGER NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP, UNIQUE(follower_id,following_id), CHECK(follower_id != following_id), FOREIGN KEY(follower_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(following_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS ratings (id INTEGER PRIMARY KEY AUTOINCREMENT, post_id INTEGER NOT NULL, user_id INTEGER NOT NULL, rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5), created_at TEXT DEFAULT CURRENT_TIMESTAMP, UNIQUE(post_id,user_id), FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS activity (id INTEGER PRIMARY KEY AUTOINCREMENT, text TEXT NOT NULL, link TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP)""")
    if not column_exists(conn, "comments", "parent_id"):
        conn.execute("ALTER TABLE comments ADD COLUMN parent_id INTEGER")
    # ================= 9.0: ПРОФИЛИ, ДОСТИЖЕНИЯ И ЛЕНТА =================
    conn.execute("""CREATE TABLE IF NOT EXISTS achievements (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, code TEXT NOT NULL, title TEXT NOT NULL, description TEXT NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,code), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS messages (id INTEGER PRIMARY KEY AUTOINCREMENT, sender_id INTEGER NOT NULL, receiver_id INTEGER NOT NULL, text TEXT NOT NULL, is_read INTEGER DEFAULT 0, created_at TEXT DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(sender_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(receiver_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS blocks (id INTEGER PRIMARY KEY AUTOINCREMENT, blocker_id INTEGER NOT NULL, blocked_id INTEGER NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP, UNIQUE(blocker_id,blocked_id), CHECK(blocker_id != blocked_id), FOREIGN KEY(blocker_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(blocked_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS comment_reactions (id INTEGER PRIMARY KEY AUTOINCREMENT, comment_id INTEGER NOT NULL, user_id INTEGER NOT NULL, reaction TEXT NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP, UNIQUE(comment_id,user_id), FOREIGN KEY(comment_id) REFERENCES comments(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE)""")
    conn.execute("""CREATE INDEX IF NOT EXISTS idx_messages_receiver ON messages(receiver_id, is_read, created_at)""")
    conn.execute("""CREATE INDEX IF NOT EXISTS idx_messages_pair ON messages(sender_id, receiver_id, created_at)""")
    conn.execute("""CREATE INDEX IF NOT EXISTS idx_reactions_comment ON comment_reactions(comment_id)""")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_comments_post_parent ON comments(post_id,parent_id,id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_follows_following ON follows(following_id,follower_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_posts_author ON posts(author_id)")

    # Старые комментарии могут не иметь user_id — это нормально.
    conn.commit()
    conn.close()


init_db()

