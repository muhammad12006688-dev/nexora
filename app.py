@app.route("/comment/<int:post_id>", methods=["POST"])
@login_required
def add_comment(post_id):

    text = request.form.get("text", "").strip()
    user = current_user()

    if not text:
        flash("Комментарий пустой.")
        return redirect(url_for("view_post", post_id=post_id))

    if len(text) > 1000:
        flash("Комментарий слишком длинный.")
        return redirect(url_for("view_post", post_id=post_id))

    conn = get_db()

    post = conn.execute(
        "SELECT id FROM posts WHERE id = ?",
        (post_id,)
    ).fetchone()

    if not post:
        conn.close()
        flash("Пост не найден.")
        return redirect(url_for("index"))

    conn.execute("""
        INSERT INTO comments
        (post_id, username, text, user_id, created_at)
        VALUES (?, ?, ?, ?, ?)
    """, (
        post_id,
        user["username"],
        text,
        user["id"],
        datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    ))

    author_row = conn.execute(
        "SELECT author_id FROM posts WHERE id = ?", (post_id,)
    ).fetchone()
    author_id = author_row["author_id"] if author_row else None

    conn.commit()
    conn.close()

    if author_id and author_id != user["id"]:
        add_notification(
            author_id,
            f"👤 {user['username']} оставил комментарий к твоему посту.",
            url_for("view_post", post_id=post_id)
        )

    check_achievements(user["id"])
    flash("Комментарий добавлен 👍")

    return redirect(url_for("view_post", post_id=post_id))


