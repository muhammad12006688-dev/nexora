def allowed_file(filename):
    return (
        "." in filename and
        filename.rsplit(".", 1)[1].lower() in ALLOWED_EXTENSIONS
    )


def current_user():
    user_id = session.get("user_id")

    if not user_id:
        return None

    conn = get_db()
    user = conn.execute(
        "SELECT * FROM users WHERE id = ?",
        (user_id,)
    ).fetchone()
    conn.close()

    return user


def add_notification(user_id, text, link=None):
    conn = get_db()
    conn.execute("""
        INSERT INTO notifications (user_id, text, link, is_read, created_at)
        VALUES (?, ?, ?, 0, ?)
    """, (user_id, text, link, datetime.now().strftime("%Y-%m-%d %H:%M:%S")))
    conn.commit()
    conn.close()


