@app.route("/login", methods=["GET", "POST"])
def login():

    if session.get("user_id"):
        return redirect(url_for("index"))

    if request.method == "POST":

        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        conn = get_db()

        user = conn.execute(
            "SELECT * FROM users WHERE username = ?",
            (username,)
        ).fetchone()

        if not user:

            conn.close()

            flash("Неверный логин или пароль.")
            return redirect(url_for("login"))

        password_ok = False

        # Новый безопасный пароль Werkzeug
        try:
            password_ok = check_password_hash(
                user["password"],
                password
            )
        except Exception:
            password_ok = False

        # Совместимость со старым SHA-256
        if not password_ok and len(user["password"]) == 64:

            old_hash = hashlib.sha256(
                password.encode()
            ).hexdigest()

            if secrets.compare_digest(
                old_hash,
                user["password"]
            ):
                password_ok = True

                # Автоматически переводим на новый хеш
                new_hash = generate_password_hash(password)

                conn.execute("""
                    UPDATE users
                    SET password = ?
                    WHERE id = ?
                """, (
                    new_hash,
                    user["id"]
                ))

                conn.commit()

        if not password_ok:

            conn.close()

            flash("Неверный логин или пароль.")
            return redirect(url_for("login"))

        session.clear()
        session["user_id"] = user["id"]

        conn.close()

        flash("Вы вошли в аккаунт 👋")

        return redirect(url_for("index"))

    body = """
    <div class="card">

        <h1>🔐 Вход</h1>

        <form method="post">

            <label>Логин</label>

            <input
                name="username"
                required
            >

            <label>Пароль</label>

            <input
                type="password"
                name="password"
                required
            >

            <button>Войти</button>

        </form>

        <br>

        <a class="btn btn-gray" href="{{ url_for('register') }}">
            Нет аккаунта? Регистрация
        </a>

    </div>
    """

    return page(
        "Вход",
        render_template_string(body)
    )


