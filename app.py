@app.route('/block/<int:user_id>', methods=['POST'])
@login_required
def block_user(user_id):
    me=current_user()
    if user_id==me['id']: return redirect(url_for('profile'))
    conn=get_db(); exists=conn.execute('SELECT 1 FROM users WHERE id=?',(user_id,)).fetchone()
    if exists:
        row=conn.execute('SELECT 1 FROM blocks WHERE blocker_id=? AND blocked_id=?',(me['id'],user_id)).fetchone()
        if row: conn.execute('DELETE FROM blocks WHERE blocker_id=? AND blocked_id=?',(me['id'],user_id)); flash('Пользователь разблокирован.')
        else: conn.execute('INSERT OR IGNORE INTO blocks(blocker_id,blocked_id) VALUES(?,?)',(me['id'],user_id)); flash('Пользователь заблокирован.')
        conn.commit()
    conn.close(); return redirect(request.referrer or url_for('profile'))

@app.route('/react/<int:comment_id>/<reaction>', methods=['POST'])
@login_required
def react_comment(comment_id,reaction):
    if reaction not in ('like','love','fire'): return redirect(request.referrer or url_for('index'))
    me=current_user(); conn=get_db(); exists=conn.execute('SELECT 1 FROM comments WHERE id=?',(comment_id,)).fetchone()
    if exists:
        old=conn.execute('SELECT reaction FROM comment_reactions WHERE comment_id=? AND user_id=?',(comment_id,me['id'])).fetchone()
        if old and old['reaction']==reaction: conn.execute('DELETE FROM comment_reactions WHERE comment_id=? AND user_id=?',(comment_id,me['id']))
        else: conn.execute('INSERT OR REPLACE INTO comment_reactions(comment_id,user_id,reaction) VALUES(?,?,?)',(comment_id,me['id'],reaction))
        conn.commit()
    conn.close(); return redirect(request.referrer or url_for('index'))


