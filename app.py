@app.route("/register", methods=["GET", "POST"])
def register():

    if session.get("user_id"):
        return redirect(url_for("index"))

    if request.method == "POST":

        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        password2 = request.form.get("password2", "")

        if not re.fullmatch(r"[A-Za-zА-Яа-яЁё0-9_]{3,20}", username):
            flash(
                "Логин: 3–20 символов, только буквы, цифры и _."
            )
            return redirect(url_for("register"))

        if len(password) < 6:
            flash("Пароль должен быть минимум 6 символов.")
            return redirect(url_for("register"))

        if password != password2:
            flash("Пароли не совпадают.")
            return redirect(url_for("register"))

        conn = get_db()

        exists = conn.execute(
            "SELECT id FROM users WHERE username = ?",
            (username,)
        ).fetchone()

        if exists:
            conn.close()
            flash("Такой пользователь уже существует.")
            return redirect(url_for("register"))

        password_hash = generate_password_hash(password)

        cursor = conn.execute("""
            INSERT INTO users
            (username, password, role, created_at)
            VALUES (?, ?, 'user', ?)
            RETURNING id
        """, (
            username,
            password_hash,
            datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        ))

        user_id = cursor.fetchone()["id"]
        conn.commit()

        conn.close()

        session["user_id"] = user_id

        flash("Аккаунт создан! Добро пожаловать 🎉")

        return redirect(url_for("profile"))

