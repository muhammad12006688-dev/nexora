    user = current_user()

    if request.method == "POST":
        new_username = request.form.get("username", "").strip()
        avatar = request.files.get("avatar")

        if not re.fullmatch(r"[A-Za-zА-Яа-яЁё0-9_]{3,20}", new_username):
            flash("Логин: 3–20 символов, только буквы, цифры и _.")
