@app.route("/like/<int:post_id>", methods=["POST"])
@login_required
def like_post(post_id):

    user = current_user()

    conn = get_db()

    already = conn.execute("""
        SELECT id
        FROM post_likes
        WHERE post_id = ?
        AND user_id = ?
    """, (post_id, user["id"])).fetchone()

    if already:
        flash("Ты уже поставил лайк ❤️")
    else:

        post = conn.execute(
            "SELECT id FROM posts WHERE id = ?",
            (post_id,)
        ).fetchone()

        if post:

            conn.execute("""
                INSERT INTO post_likes
                (post_id, user_id)
                VALUES (?, ?)
            """, (
                post_id,
                user["id"]
            ))

            conn.execute("""
                UPDATE posts
                SET likes = likes + 1
                WHERE id = ?
            """, (post_id,))

            conn.commit()

            flash("Лайк поставлен ❤️")

        else:
            flash("Пост не найден.")

    conn.close()

    return redirect(url_for("view_post", post_id=post_id))


